let currentApiNodeIndex = Math.floor(Math.random() * groqConfigs.length);

async function callGroq(prompt, maxRetries = 3) {
  let lastError;

  for (let attempt = 0; attempt < maxRetries; attempt++) {
    for (let i = 0; i < groqConfigs.length; i++) {
      const config =
        groqConfigs[(currentApiNodeIndex + i) % groqConfigs.length];

      try {
        const response = await fetch(
          "https://api.groq.com/openai/v1/chat/completions",
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              Authorization: `Bearer ${config.key}`,
            },
            body: JSON.stringify({
              model: config.model,
              messages: [
                {
                  role: "system",
                  content:
                    "You are a strict, deterministic code execution engine and compiler. You execute code flawlessly. CRITICAL FOR PATTERNS: If the code prints ASCII art, shapes (like a butterfly), or uses string multiplication (e.g., '*' * i + ' ' * space + '*' * i), you MUST trace the exact mathematical character count for EVERY single line. NEVER skip the right side of the shape. NEVER truncate spaces. DO NOT approximate. CRITICAL: You MUST output ALL lines generated by loops. If a countdown loop goes to 1, you MUST print the line for 1. NEVER terminate output prematurely. Output ONLY the raw stdout/stderr text without markdown formatting unless specifically instructed to return JSON. If loops exceed 1000 iterations, throw a TimeoutException. UNDER NO CIRCUMSTANCES SHOULD YOU EXPLAIN THE CODE OR PROVIDE CONVERSATIONAL TEXT. IF THE CODE PRODUCES NO OUTPUT, RETURN AN EMPTY STRING.",
                },
                { role: "user", content: prompt },
              ],
              temperature: 0.05,
              max_tokens: 4096,
              top_p: 1,
            }),
          }
        );

        if (!response.ok) {
          const errData = await response.json().catch(() => ({}));
          if (response.status === 429) throw new Error("Rate Limited");
          throw new Error(
            `API ${config.model} Failed: ${
              errData.error?.message || response.status
            }`
          );
        }

        const data = await response.json();
        currentApiNodeIndex = (currentApiNodeIndex + 1) % groqConfigs.length;

        return data.choices?.[0]?.message?.content || "";
      } catch (error) {
        console.warn(
          `Execution Node Fallback: Key/Model failed (${config.model}). Shifting...`,
          error.message
        );
        lastError = error;
        continue;
      }
    }
    console.warn(
      `All execution nodes busy. Retrying attempt ${attempt + 1} in ${Math.pow(
        2,
        attempt
      )}s...`
    );
    await new Promise((resolve) =>
      setTimeout(resolve, 1000 * Math.pow(2, attempt))
    );
  }

  throw new Error(
    `Critical: All execution nodes exhausted or heavily rate-limited. Last error: ${lastError?.message}`
  );
}

