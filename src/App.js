const playCheatAlarm = () => {
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    const ctx = new AudioContext();

    const playSiren = (freq1, freq2, startTime, duration) => {
      const osc1 = ctx.createOscillator();
      const osc2 = ctx.createOscillator();
      const gain = ctx.createGain();

      osc1.type = "square";
      osc2.type = "sawtooth";

      osc1.frequency.setValueAtTime(freq1, startTime);
      osc1.frequency.linearRampToValueAtTime(freq2, startTime + duration / 2);
      osc1.frequency.linearRampToValueAtTime(freq1, startTime + duration);

      osc2.frequency.setValueAtTime(freq1 * 1.5, startTime);
      osc2.frequency.linearRampToValueAtTime(
        freq2 * 1.5,
        startTime + duration / 2
      );
      osc2.frequency.linearRampToValueAtTime(freq1 * 1.5, startTime + duration);

      gain.gain.setValueAtTime(1.0, startTime);
      gain.gain.setValueAtTime(1.0, startTime + duration - 0.1);
      gain.gain.linearRampToValueAtTime(0.01, startTime + duration);

      osc1.connect(gain);
      osc2.connect(gain);
      gain.connect(ctx.destination);

      osc1.start(startTime);
      osc2.start(startTime);
      osc1.stop(startTime + duration);
      osc2.stop(startTime + duration);
    };

    const now = ctx.currentTime;
    for (let i = 0; i < 6; i++) {
      playSiren(1200, 2000, now + i * 0.4, 0.4);
    }
  } catch (e) {
    console.warn("Audio Context blocked.", e);
  }
};

// --- DRAGGABLE RESIZABLE GUI WINDOW COMPONENT ---
const DraggableGUIWindow = ({ title, html, onClose }) => {
  const [pos, setPos] = useState({
    x: Math.max(0, window.innerWidth / 2 - 250),
    y: Math.max(0, window.innerHeight / 2 - 200),
  });
  const [isDragging, setIsDragging] = useState(false);
  const [rel, setRel] = useState({ x: 0, y: 0 });
  const [isMinimized, setIsMinimized] = useState(false);

  const onMouseDown = (e) => {
    if (e.target.tagName === "BUTTON" || e.target.closest("button")) return;
    setIsDragging(true);
    setRel({
      x: e.pageX - pos.x,
      y: e.pageY - pos.y,
    });
    e.stopPropagation();
    e.preventDefault();
  };

  const onMouseUp = () => setIsDragging(false);

  const onMouseMove = (e) => {
    if (!isDragging) return;
    setPos({
      x: e.pageX - rel.x,
      y: e.pageY - rel.y,
    });
    e.stopPropagation();
    e.preventDefault();
  };

  useEffect(() => {
    if (isDragging) {
      document.addEventListener("mousemove", onMouseMove);
      document.addEventListener("mouseup", onMouseUp);
    } else {
      document.removeEventListener("mousemove", onMouseMove);
      document.removeEventListener("mouseup", onMouseUp);
    }
    return () => {
      document.removeEventListener("mousemove", onMouseMove);
      document.removeEventListener("mouseup", onMouseUp);
    };
  }, [isDragging, rel]);

  return (
    <div
      className={`fixed z-[300] flex flex-col bg-white dark:bg-zinc-900 border border-zinc-300 dark:border-zinc-700 rounded-lg shadow-2xl overflow-hidden transition-all ${
        isMinimized
          ? "w-64 h-12 resize-none"
          : "w-[90vw] sm:w-[500px] h-[60vh] sm:h-[400px] min-w-[300px] min-h-[200px]"
      }`}
      style={{
        left: pos.x,
        top: pos.y,
        resize: isMinimized ? "none" : "both",
        overflow: "hidden",
      }}
    >
      <div
        onMouseDown={onMouseDown}
        className="h-12 bg-zinc-100 dark:bg-zinc-800 flex items-center justify-between px-3 cursor-move border-b border-zinc-200 dark:border-zinc-700 flex-shrink-0"
      >
        <span className="font-bold text-sm text-zinc-800 dark:text-zinc-200 flex items-center gap-2">
          <AppWindow size={16} className="text-blue-500" /> {title}
        </span>
        <div className="flex gap-2">
          <button
            onClick={() => setIsMinimized(!isMinimized)}
            className="p-1 hover:bg-zinc-200 dark:hover:bg-zinc-700 rounded text-zinc-500 transition-colors"
          >
            {isMinimized ? <Maximize2 size={16} /> : <Minus size={16} />}
          </button>
          <button
            onClick={onClose}
            className="p-1 hover:bg-red-500 hover:text-white rounded text-zinc-500 transition-colors"
          >
            <X size={16} />
          </button>
        </div>
      </div>
      {!isMinimized && (
        <div className="flex-1 bg-white relative">
          {isDragging && (
            <div className="absolute inset-0 z-10 cursor-move"></div>
          )}
          <iframe
            title="GUI Preview"
            srcDoc={html}
            sandbox="allow-scripts allow-same-origin"
            className="w-full h-full border-none"
          />
        </div>
      )}
    </div>
  );
};

